#!/usr/bin/env python3
"""Regenerate synthetic, speech-free probes from the HF Nemotron front-end.

Reference: transformers 5.22.2, models/nemotron_asr_streaming/
feature_extraction_nemotron_asr_streaming.py, _torch_extract_fbank_features.
Uses torch 2.8.0, numpy 2.0.2 and librosa 0.11.0. No model or audio download.
Padding is applied after pre-emphasis, as the processor's audio-length mask
does. The extra frames complete the encoder's fixed 32-frame final window.
"""

from pathlib import Path
import numpy as np
import torch
import librosa

torch.set_num_threads(1)
filters = torch.from_numpy(librosa.filters.mel(
    sr=16000, n_fft=512, n_mels=128, fmin=0, fmax=8000, norm="slaney"))
window = torch.hann_window(400, periodic=False)
lines = [
    "// Generated by scripts/generate_nemotron_mel_contract.py.",
    "// torch 2.8.0, numpy 2.0.2, librosa 0.11.0; no recording data.",
    "// {input samples, frame, mel bin, reference log-mel value}",
]
for length in (37, 5120, 5217):
    state = 0x12345678
    values = []
    for i in range(length):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        value = np.float32((state >> 8) / (1 << 24) - .5) / np.float32(32)
        if length // 3 <= i < min(length - 1, length // 3 + 512):
            value = np.float32(0)
        values.append(value)
    values[0], values[-1] = np.float32(.03125), np.float32(.125)
    x = torch.from_numpy(np.asarray(values, dtype=np.float32))
    emphasized = torch.cat((x[:1], x[1:] - .97 * x[:-1]))
    total_frames = ((length + 5119) // 5120) * 32
    emphasized = torch.nn.functional.pad(emphasized, (0, total_frames * 160 + 256 - length))
    stft = torch.stft(emphasized, 512, hop_length=160, win_length=400,
        window=window, return_complex=True, pad_mode="constant", center=True)
    power = torch.view_as_real(stft).pow(2).sum(-1).sqrt().pow(2)
    mel = torch.log(filters @ power + 2 ** -24)
    frames = sorted({f for f in (0, 1, 2, 30, 31, 32, 33, length // 160, total_frames - 1)
                     if f < total_frames})
    for frame in frames:
        for band in (0, 1, 17, 31, 64, 96, 127):
            lines.append(f"{{{length}, {frame}, {band}, {mel[band, frame].item():.9g}f}},")
destination = Path(__file__).resolve().parents[1] / "tests/data/nemotron_mel_reference.inc"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(lines) + "\n")
print(destination)
